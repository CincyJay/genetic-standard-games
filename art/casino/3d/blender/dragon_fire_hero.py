def mat(name,c,metal=0,rough=.35,emit=None,tex=None):
 m=bpy.data.materials.new(name);m.use_nodes=True;p=m.node_tree.nodes.get('Principled BSDF')
 p.inputs['Base Color'].default_value=(*c,1);p.inputs['Metallic'].default_value=metal;p.inputs['Roughness'].default_value=rough
 if emit:p.inputs['Emission Color'].default_value=(*emit,1);p.inputs['Emission Strength'].default_value=1.6
 if tex:
  im=bpy.data.images.load(os.path.join(TEX,tex),check_existing=True);im.pack()
  node=m.node_tree.nodes.new('ShaderNodeTexImage');node.image=im
  m.node_tree.links.new(node.outputs['Color'],p.inputs['Base Color'])
  m.node_tree.links.new(node.outputs['Color'],p.inputs['Emission Color'])
  p.inputs['Emission Strength'].default_value=.75
 return m
