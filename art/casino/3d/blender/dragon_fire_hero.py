# Curved displays are subdivided into 32 strips; front screen has continuous UV.
def bowed_display(n,width,height,zc,yc,material):
 verts=[];uvs=[];faces=[];segments=32
 for j in range(segments+1):
  u=j/segments;x=(u-.5)*width
  # convex forward bow at centre, curved back at the edges
  y=yc-.036*(1-(2*u-1)**2)
  for v in (0,1):verts.append((x,y,zc+(v-.5)*height));uvs.append((u,v))
 for j in range(segments):faces.append((j*2,(j+1)*2,(j+1)*2+1,j*2+1))
 mesh=bpy.data.meshes.new(n);mesh.from_pydata(verts,[],faces);mesh.update()
 layer=mesh.uv_layers.new()
 for poly in mesh.polygons:
  for l in poly.loop_indices:layer.data[l].uv=uvs[mesh.loops[l].vertex_index]
 o=bpy.data.objects.new(n,mesh);bpy.context.collection.objects.link(o);o.data.materials.append(material)
 return o
