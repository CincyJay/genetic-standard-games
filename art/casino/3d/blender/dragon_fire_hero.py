def bevel(o,r=.015,seg=4):
 m=o.modifiers.new('manufactured edge radii','BEVEL');m.width=r;m.segments=seg
 o.modifiers.new('weighted face normals','WEIGHTED_NORMAL')
def box(n,loc,size,m,r=.012):
 bpy.ops.mesh.primitive_cube_add(size=1,location=loc);o=bpy.context.object;o.name=n;o.dimensions=size
 bpy.ops.object.transform_apply(location=False,rotation=False,scale=True);o.data.materials.append(m)
 if r:bevel(o,r)
 return o
def tube(n,points,r,m,closed=False):
 c=bpy.data.curves.new(n,'CURVE');c.dimensions='3D';c.bevel_depth=r;c.bevel_resolution=3
 s=c.splines.new('POLY');s.points.add(len(points)-1)
 for p,xyz in zip(s.points,points):p.co=(*xyz,1)
 s.use_cyclic_u=closed;o=bpy.data.objects.new(n,c);bpy.context.collection.objects.link(o);o.data.materials.append(m)
 return o
def panel(n,outline,depth,material,xcenter=0):
 # outline coordinates (Y,Z); extruded along X
 v=[(xcenter+x,y,z) for x in (-depth/2,depth/2) for y,z in outline]
 N=len(outline);f=[tuple(reversed(range(N))),tuple(range(N,2*N))]
 f.extend((i,(i+1)%N,(i+1)%N+N,i+N) for i in range(N))
 mesh=bpy.data.meshes.new(n);mesh.from_pydata(v,[],f);mesh.update()
 o=bpy.data.objects.new(n,mesh);bpy.context.collection.objects.link(o);o.data.materials.append(material);bevel(o,.026,5);return o
def quad(n,verts,material):
 mesh=bpy.data.meshes.new(n);mesh.from_pydata(verts,[],[(0,1,2,3)]);mesh.update()
 uv=mesh.uv_layers.new()
 for poly in mesh.polygons:
  for loop in poly.loop_indices:
   vi=mesh.loops[loop].vertex_index;uv.data[loop].uv=((0,0),(1,0),(1,1),(0,1))[vi]
 o=bpy.data.objects.new(n,mesh);bpy.context.collection.objects.link(o);o.data.materials.append(material)
 return o
